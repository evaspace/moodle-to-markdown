def _link_key(name):
    s = unicodedata.normalize('NFD', (name or '').replace('*', ''))
    s = ''.join(ch for ch in s if not unicodedata.combining(ch)).lower()
    s = re.sub(r'^\d+_', '', s)
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    return s


def course_url(category_name, subcategory_name=None):
    """URL of the course page a card comes from: its chapter if known, else the course index."""
    cat_key = _link_key(category_name)
    path = (COURSE_LINKS.get(f"{cat_key}||{_link_key(subcategory_name)}") if subcategory_name else None) \
        or COURSE_LINKS.get(cat_key)
    return '/cours/' + quote(path) if path else None

