    with db() as conn:
        if not conn.execute("SELECT 1 FROM card WHERE id = ?", (card_id,)).fetchone():
            return jsonify(error='carte inconnue'), 404
        existing = conn.execute("SELECT id FROM favorite WHERE card_id = ? AND uid = ?", (card_id, uid())).fetchone()
