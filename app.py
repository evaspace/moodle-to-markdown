def grouped_categories(conn):
    """Categories with cards, duplicates merged by display name, grouped into themes."""
    cats = conn.execute('''
        SELECT cat.id, cat.name, COUNT(c.id) AS n
        FROM category cat
        JOIN subcategory sc ON sc.category_id = cat.id
        JOIN card c ON c.subcategory_id = sc.id
        WHERE c.status = 0
        GROUP BY cat.id''').fetchall()

    merged = {}
    for cat in cats:
        name = clean_name(cat['name'])
        entry = merged.setdefault(name.casefold(), {
            'id': cat['id'], 'ids': [], 'name': name, 'n': 0,
            'theme': theme_for(name), 'subcategories': [], 'source_url': None})
        entry['ids'].append(cat['id'])
        entry['n'] += cat['n']
        entry['source_url'] = entry['source_url'] or course_url(cat['name'])
        subs = conn.execute('''
            SELECT sc.id, sc.name, COUNT(c.id) AS n
            FROM subcategory sc
            JOIN card c ON c.subcategory_id = sc.id
            WHERE sc.category_id = ? AND c.status = 0
            GROUP BY sc.id''', (cat['id'],)).fetchall()
        entry['subcategories'] += [{'id': s['id'], 'name': clean_name(s['name']), 'n': s['n']}
                                   for s in subs]

    themes = {}
    for entry in merged.values():
        entry['subcategories'].sort(key=lambda s: s['name'].casefold())
        theme = themes.setdefault(entry['theme']['id'], {**entry['theme'], 'n': 0, 'categories': []})
        theme['n'] += entry['n']
        theme['categories'].append(entry)
    for theme in themes.values():
        rank = syllabus_rank if theme['id'] == 'maths' else (lambda _n: 0)
        theme['categories'].sort(key=lambda e: (rank(e['name']), e['name'].casefold()))
    return sorted(themes.values(), key=lambda t: theme_order(t['id']))


