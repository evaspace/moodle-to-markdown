DOC_ASSET_EXTENSIONS = {'.pdf', '.docx', '.png', '.jpg', '.jpeg', '.gif', '.svg', '.webp'}
MATHJAX_BLOCK_RE = re.compile(r'\[\s*mathjax\s*\](.*?)\[\s*/mathjax\s*\]', re.S | re.I)
MATHJAX_INLINE_RE = re.compile(r'\[\s*mathjaxinline\s*\](.*?)\[\s*/mathjaxinline\s*\]', re.S | re.I)
MATH_SPAN_RE = re.compile(r'\$\$.+?\$\$|\$[^$\n]+?\$|\\\[.+?\\\]|\\\(.+?\\\)', re.S)


def render_markdown_with_math(source):
    """Markdown -> HTML sans abîmer le LaTeX (_, \\, *) ; convertit les balises Moodle [mathjax]."""
    source = MATHJAX_BLOCK_RE.sub(lambda m: '$$' + m.group(1).strip() + '$$', source)
    source = MATHJAX_INLINE_RE.sub(lambda m: '$' + m.group(1).strip() + '$', source)
    spans = []

    def stash(m):
        # l'export Moodle échappe \_ et \* (Markdown) : invalide en LaTeX, on les rétablit
        spans.append(re.sub(r'\\([_*])', r'\1', m.group(0)))
        return f'MATHSPAN{len(spans) - 1}X'

    html = markdown.markdown(MATH_SPAN_RE.sub(stash, source),
                             extensions=['tables', 'fenced_code', 'sane_lists'])
    html = bleach.clean(html, tags=DOC_TAGS, attributes=DOC_ATTRIBUTES,
                        protocols=['http', 'https', 'mailto'], strip=True)
    return re.sub(r'MATHSPAN(\d+)X', lambda m: html_escape(spans[int(m.group(1))], quote=False), html)


def _plain(text):
    """Markdown line -> plain text: links, emphasis and emoji removed."""
    text = re.sub(r'!?\[([^\]]*)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'[*_`>]+', '', text)
    text = ''.join(c for c in text if unicodedata.category(c) not in ('So', 'Mn') and c != '\ufe0f')
    return ' '.join(text.split())


def doc_description(source, title):
    """First real paragraph of a note, else a summary of its sections (index pages are only lists)."""
    for line in source.splitlines():
        line = line.strip()
        if line and line[0] not in '#->|*!<' and not re.search(r'synchronis|Dernière|Astuce', line):
            text = _plain(line)
            if len(text) >= 40:
                return (text[:155].rsplit(' ', 1)[0] + '…') if len(text) > 155 else text
    parts, current = [], None
    for line in source.splitlines():
        if line.startswith('## '):
            current = [_plain(line[3:]).lower(), 0]
            parts.append(current)
        elif current and line.lstrip().startswith('- '):
            current[1] += 1
    summary = ', '.join(f'{name} ({n})' for name, n in parts if n and 'statistiques' not in name)
    base = f"Notes de cours EPITA : {_plain(title)}"
    return f"{base}. Contenu : {summary}." if summary else base + "."


@app.route('/cours/')
@app.route('/cours/<path:relative_path>')
def course_document(relative_path='README.md'):
    """Render Markdown documents from the Moodle export, without exposing other files."""
    root = DOCS_ROOT.resolve()
    target = (root / relative_path).resolve()
    if not target.is_relative_to(root) or not target.is_file():
        abort(404)
    if target.suffix.lower() in DOC_ASSET_EXTENSIONS:
        return send_from_directory(root, target.relative_to(root).as_posix())
    if target.suffix.lower() != '.md':
        abort(404)
    try:
        source = target.read_text(encoding='utf-8')
    except (OSError, UnicodeError):
        abort(404)
    safe_html = render_markdown_with_math(source)
    title_match = re.search(r'^\s*#\s+(.+?)\s*#*\s*$', source, re.M)
    title = title_match.group(1) if title_match else target.stem
    description = doc_description(source, title)
    canonical = f"https://epitadoomscrolling.pierref.eu/cours/{relative_path}"
    ld = {"@context": "https://schema.org", "@type": "LearningResource", "name": _plain(title), "url": canonical,
          "inLanguage": "fr", "learningResourceType": "Course notes",
          "author": {"@type": "Person", "name": "Morgan Pierrefeu", "url": "https://pierref.eu/"},
          "isPartOf": {"@type": "WebSite", "name": "Epita Doomscrolling", "url": "https://epitadoomscrolling.pierref.eu/"}}
    if description:
        ld["description"] = description
    return render_template('docs.html', title=title, content=safe_html,
                           relative_path=relative_path, description=description, canonical=canonical,
                           jsonld=json.dumps(ld, ensure_ascii=False).replace('</', '<\\/'))


